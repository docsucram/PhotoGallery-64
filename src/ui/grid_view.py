def get_windows_open_with_apps(extension: str) -> list[tuple[str, str]]:
    """Returns list of (friendly_name, app_cmd) from Windows Registry for the extension."""
    if sys.platform != "win32":
        return []
    try:
        import winreg
        clean_ext = ("." + extension.lstrip(".")).lower()
        seen: set[str] = set()
        apps: list[tuple[str, str]] = []

        def _resolve_name(exe_name: str) -> str:
            try:
                with winreg.OpenKey(winreg.HKEY_CLASSES_ROOT, f"Applications\\{exe_name}") as k:
                    name, _ = winreg.QueryValueEx(k, "FriendlyAppName")
                    if name:
                        return str(name)
            except OSError:
                pass
            stem = exe_name.lower().replace(".exe", "")
            known = {
                "mspaint": "Paint",
                "photos": "Photos",
                "photostudio": "Photo Studio",
                "i_view64": "IrfanView",
                "i_view32": "IrfanView",
                "chrome": "Google Chrome",
                "msedge": "Microsoft Edge",
                "firefox": "Firefox",
                "vlc": "VLC media player",
                "wmplayer": "Windows Media Player",
                "explorer": "Windows Explorer",
            }
            if stem in known:
                return known[stem]
            if stem.startswith("microsoft.windows.photos"):
                return "Photos"
            if "pickerhost" in stem or stem.startswith("microsoft.autogenerated") or "python" in stem:
                return ""
            return stem.capitalize()

        for root in (winreg.HKEY_CURRENT_USER, winreg.HKEY_CLASSES_ROOT):
            try:
                kp = f"Software\\Microsoft\\Windows\\CurrentVersion\\Explorer\\FileExts\\{clean_ext}\\OpenWithList"
                with winreg.OpenKey(root, kp) as k:
                    num = winreg.QueryInfoKey(k)[1]
                    for i in range(num):
                        val_name, val_data, _ = winreg.EnumValue(k, i)
                        if val_name != "MRUList" and isinstance(val_data, str) and val_data not in seen:
                            seen.add(val_data)
                            fname = _resolve_name(val_data)
                            if fname:
                                apps.append((fname, val_data))
            except OSError:
                pass

        return apps
    except Exception:
        return []


def _build_star_polygon(
    center_x: float, center_y: float, outer_r: float, inner_r: float
) -> QPolygonF:
    points: list[QPointF] = []
    for i in range(10):
        angle_deg = -90.0 + (i * 36.0)
        rad = math.radians(angle_deg)
        r = outer_r if i % 2 == 0 else inner_r
        points.append(
            QPointF(center_x + r * math.cos(rad), center_y + r * math.sin(rad))
        )
    return QPolygonF(points)


class MediaCardDelegate(QStyledItemDelegate):
    """
    Custom QStyledItemDelegate rendering WLPG Polaroid cards (or Mosaic tiles),
    collapsible 38px group headers, hover checkboxes, flag pins, and 5-star ratings.
    """

    rating_clicked = Signal(int, int)         # media_id, rating (1..5 or 0 to clear)
    flag_toggled = Signal(int, int)           # media_id, new_flag (0 or 1)
    checkbox_toggled = Signal(int, bool)      # media_id, checked
    group_header_clicked = Signal(str)        # group_key
    caption_changed = Signal(int, str)        # media_id, new_caption

    STAR_BAR_WIDTH = 72
    STAR_BAR_HEIGHT = 16

    def __init__(
        self, pixmap_cache: LruCache, parent: QWidget | None = None
    ) -> None:
        super().__init__(parent)
        self.pixmap_cache = pixmap_cache
        self._cell_size = QSize(182, 204)
        self._visible_details: set[str] = {"rating", "flag"}
        self._layout_mode: Literal["wlpg_grid", "mosaic"] = "wlpg_grid"
        self._hover_row: int = -1
        self._hover_star: int = 0
        self._hover_caption: bool = False
        self.face_crop_person_id: int | None = None
        self.thumb_repo: Any | None = None
        self._face_crop_cache: dict[tuple[int, int], QPixmap] = {}

    def set_face_crop_person_id(self, person_id: int | None) -> None:
        self.face_crop_person_id = person_id

    def set_cell_size(self, size: QSize) -> None:
        self._cell_size = size

    def set_visible_details(self, details: set[str]) -> None:
        self._visible_details = set(details)

    def set_layout_mode(self, mode: Literal["wlpg_grid", "mosaic"]) -> None:
        self._layout_mode = mode

    # -------------------------------------------------------------------------
    # Deterministic Hit-Test Geometry Helpers
    # -------------------------------------------------------------------------
    @staticmethod
    def checkbox_rect(card_rect: QRect) -> QRect:
        return QRect(card_rect.left() + 6, card_rect.top() + 6, 16, 16)

    @staticmethod
    def flag_rect(card_rect: QRect) -> QRect:
        return QRect(card_rect.right() - 22, card_rect.top() + 6, 16, 16)

    @classmethod
    def stars_bar_rect(cls, card_rect: QRect) -> QRect:
        x = card_rect.center().x() - (cls.STAR_BAR_WIDTH // 2)
        y = card_rect.bottom() - cls.STAR_BAR_HEIGHT - 3
        return QRect(x, y, cls.STAR_BAR_WIDTH, cls.STAR_BAR_HEIGHT)

    @classmethod
    def caption_rect(cls, card_rect: QRect, has_stars: bool = True) -> QRect:
        y_bot = card_rect.bottom() - (cls.STAR_BAR_HEIGHT + 6 if has_stars else 4)
        return QRect(card_rect.left() + 6, y_bot - 16, card_rect.width() - 12, 16)

    @classmethod
    def star_index_at(cls, stars_rect: QRect, pos: QPoint) -> int | None:
        if not stars_rect.contains(pos):
            return None
        rel_x = max(0, pos.x() - stars_rect.left())
        star_w = cls.STAR_BAR_WIDTH / 5.0
        idx = int(rel_x // star_w) + 1
        return max(1, min(5, idx))

    def sizeHint(
        self, option: QStyleOptionViewItem, index: QModelIndex
    ) -> QSize:
        if index.data(CatalogRoles.IsGroupHeaderRole):
            return QSize(option.rect.width() or 800, CatalogListModel.HEADER_HEIGHT)
        if self._layout_mode == "mosaic":
            mrect: QRect | None = index.data(CatalogRoles.MosaicRectRole)
            if isinstance(mrect, QRect) and mrect.isValid():
                return mrect.size()
        return self._cell_size

    # -------------------------------------------------------------------------
    # Painting
    # -------------------------------------------------------------------------
    def paint(
        self,
        painter: QPainter,
        option: QStyleOptionViewItem,
        index: QModelIndex,
    ) -> None:
        if not index.isValid():
            return
        if index.data(CatalogRoles.IsHeaderSpacerRole):
            return
        if index.data(CatalogRoles.IsGroupHeaderRole):
            self._paint_group_header(painter, option, index)
            return
        self._paint_media_card(painter, option, index)

    def _paint_group_header(
        self,
        painter: QPainter,
        option: QStyleOptionViewItem,
        index: QModelIndex,
    ) -> None:
        painter.save()
        painter.setRenderHint(QPainter.Antialiasing, True)

        group_key = str(index.data(CatalogRoles.GroupKeyRole) or "")
        total_cnt = int(index.data(CatalogRoles.GroupCountRole) or 0)
        sel_cnt = int(index.data(CatalogRoles.GroupSelectedCountRole) or 0)
        collapsed = bool(index.data(CatalogRoles.GroupCollapsedRole))

        row_rect = option.rect

        # Chevron (› or ⌄)
        chevron = "›" if collapsed else "⌄"
        chevron_font = QFont("Segoe UI", 12, QFont.Bold)
        painter.setFont(chevron_font)
        painter.setPen(QColor("#1E395B"))
        painter.drawText(
            QRect(row_rect.left() + 2, row_rect.top() + 2, 16, 28),
            Qt.AlignLeft | Qt.AlignVCenter,
            chevron,
        )

        # WLPG Section Title (Segoe UI Light-style 14pt blue)
        title_font = QFont("Segoe UI", 14, QFont.Normal)
        painter.setFont(title_font)
        painter.setPen(QColor("#29588C"))
        fm_title = painter.fontMetrics()
        title_w = fm_title.horizontalAdvance(group_key) + 8
        title_rect = QRect(row_rect.left() + 18, row_rect.top() + 2, title_w, 28)
        painter.drawText(title_rect, Qt.AlignLeft | Qt.AlignVCenter, group_key)

        # Item & selection count subtitle
        item_word = "item" if total_cnt == 1 else "items"
        if sel_cnt > 0:
            sub_text = f"({total_cnt} {item_word}, {sel_cnt} selected)"
        else:
            sub_text = f"({total_cnt} {item_word})"

        sub_font = QFont("Segoe UI", 9)
        painter.setFont(sub_font)
        painter.setPen(QColor("#6D6D6D"))
        fm_sub = painter.fontMetrics()
        sub_w = fm_sub.horizontalAdvance(sub_text) + 12
        sub_rect = QRect(title_rect.right() + 4, row_rect.top() + 6, sub_w, 24)
        painter.drawText(sub_rect, Qt.AlignLeft | Qt.AlignVCenter, sub_text)

        # Subtle WLPG horizontal section divider line to the right of the subtitle
        line_x = sub_rect.right() + 8
        if line_x < row_rect.right() - 12:
            line_y = row_rect.top() + 20
            painter.setPen(QPen(QColor("#E5EEF7"), 1))
            painter.drawLine(line_x, line_y, row_rect.right() - 8, line_y)

        painter.restore()

    def _paint_media_card(
        self,
        painter: QPainter,
        option: QStyleOptionViewItem,
        index: QModelIndex,
    ) -> None:
        painter.save()
        painter.setRenderHint(QPainter.Antialiasing, True)
        painter.setRenderHint(QPainter.SmoothPixmapTransform, True)

        card_rect = option.rect.adjusted(2, 2, -2, -2)
        is_selected = bool(option.state & QStyle.State_Selected)
        is_hovered = bool(option.state & QStyle.State_MouseOver)

        media_id = index.data(CatalogRoles.MediaIdRole)
        rating = int(index.data(CatalogRoles.RatingRole) or 0)
        flag = int(index.data(CatalogRoles.FlagRole) or 0)
        is_video = bool(index.data(CatalogRoles.IsVideoRole))

        # 1. Card Outer Background / Aero Selection & Hover Frame
        # Per reference main_ui.png & find_ui.png: unselected cards have NO outer box border;
        # hovered cards show a faint Aero outline, and selected cards show the Aero sky-blue box.
        if is_selected:
            grad = QLinearGradient(card_rect.topLeft(), card_rect.bottomLeft())
            grad.setColorAt(0.0, QColor("#E4F3FF"))
            grad.setColorAt(1.0, QColor("#C6E4FF"))
            painter.setBrush(grad)
            painter.setPen(QPen(QColor("#6CB8FF"), 1.2))
            painter.drawRoundedRect(card_rect, 3, 3)
        elif is_hovered:
            grad = QLinearGradient(card_rect.topLeft(), card_rect.bottomLeft())
            grad.setColorAt(0.0, QColor("#F6FBFF"))
            grad.setColorAt(1.0, QColor("#E8F4FF"))
            painter.setBrush(grad)
            painter.setPen(QPen(QColor("#B8DCFF"), 1.0))
            painter.drawRoundedRect(card_rect, 3, 3)

        # 2. Compute Image Area vs Bottom Details/Rating Area
        has_stars = ("rating" in self._visible_details or "all" in self._visible_details)
        has_caption = ("caption" in self._visible_details or "all" in self._visible_details)
        bottom_reserve = 6
        if has_stars:
            bottom_reserve += 20
        if has_caption:
            bottom_reserve += 18

        extra_lines: list[str] = []
        if "filename" in self._visible_details or "all" in self._visible_details:
            extra_lines.append(str(index.data(CatalogRoles.FilenameRole) or ""))
        if "size" in self._visible_details or "all" in self._visible_details:
            extra_lines.append(format_file_size(int(index.data(CatalogRoles.FileSizeRole) or 0)))
        if "dimensions" in self._visible_details or "all" in self._visible_details:
            dims = str(index.data(CatalogRoles.DimensionsRole) or "")
            if dims:
                extra_lines.append(dims)
        if "date_taken" in self._visible_details or "all" in self._visible_details:
            dt_epoch = index.data(CatalogRoles.DateTakenRole)
            if dt_epoch:
                extra_lines.append(_epoch_to_datetime_utc(int(dt_epoch)).strftime("%d/%m/%Y %H:%M"))
        if "date_modified" in self._visible_details or "all" in self._visible_details:
            mtime = index.data(CatalogRoles.DateModifiedRole)
            if mtime:
                extra_lines.append(_epoch_to_datetime_utc(int(mtime)).strftime("%d/%m/%Y %H:%M"))

        bottom_reserve += len(extra_lines) * 14
        if self._layout_mode == "mosaic":
            img_box = card_rect.adjusted(3, 3, -3, -bottom_reserve)
        else:
            img_box = card_rect.adjusted(10, 10, -10, -bottom_reserve)

        # 3. Draw Thumbnail Pixmap (from LruCache or face crop) with WLPG Drop Shadow
        pixmap: QPixmap | None = None
        if self.face_crop_person_id is not None and media_id is not None:
            key = (int(media_id), int(self.face_crop_person_id))
            if key in self._face_crop_cache:
                pixmap = self._face_crop_cache[key]
            elif self.thumb_repo is not None:
                blob = self.thumb_repo.get_face_thumbnail_for_media_person(media_id, self.face_crop_person_id)
                if blob:
                    pm = QPixmap()
                    pm.loadFromData(blob)
                    self._face_crop_cache[key] = pm
                    pixmap = pm

        if pixmap is None and media_id is not None:
            pixmap = self.pixmap_cache.get(media_id)
        if pixmap is not None and not pixmap.isNull() and img_box.width() > 8 and img_box.height() > 8:
            if self._layout_mode == "mosaic":
                scaled_sz = pixmap.size().scaled(img_box.size(), Qt.KeepAspectRatioByExpanding)
                target_rect = img_box
            else:
                scaled_sz = pixmap.size().scaled(img_box.size(), Qt.KeepAspectRatio)
                # Align photo toward the bottom of img_box (right above the 5 stars, like WLPG!)
                target_rect = QRect(
                    img_box.center().x() - scaled_sz.width() // 2,
                    img_box.bottom() - scaled_sz.height(),
                    scaled_sz.width(),
                    scaled_sz.height(),
                )

            # Multi-layer soft WLPG drop shadow behind photo
            painter.setPen(Qt.NoPen)
            painter.setBrush(QColor(0, 0, 0, 26))
            painter.drawRect(target_rect.adjusted(2, 2, 4, 4))
            painter.setBrush(QColor(0, 0, 0, 48))
            painter.drawRect(target_rect.adjusted(1, 1, 2, 2))

            if self._layout_mode == "mosaic":
                painter.save()
                painter.setClipRect(target_rect)
                src_x = max(0, (scaled_sz.width() - target_rect.width()) // 2)
                src_y = max(0, (scaled_sz.height() - target_rect.height()) // 2)
                scaled_pix = pixmap.scaled(scaled_sz, Qt.IgnoreAspectRatio, Qt.SmoothTransformation)
                painter.drawPixmap(
                    target_rect.topLeft(),
                    scaled_pix,
                    QRect(src_x, src_y, target_rect.width(), target_rect.height()),
                )
                painter.restore()
            else:
                painter.drawPixmap(target_rect, pixmap)

            painter.setBrush(Qt.NoBrush)
            painter.setPen(QPen(QColor("#B8B8B8"), 1))
            painter.drawRect(target_rect)
        else:
            # Subtle placeholder while worker decodes WebP
            painter.setBrush(QColor("#F4F6F9"))
            painter.setPen(QPen(QColor("#DCE2EA"), 1))
            painter.drawRect(img_box)
            if is_video:
                painter.setPen(QColor("#666666"))
                painter.drawText(img_box, Qt.AlignCenter, "🎬 VIDEO")

        # 4. Top-Left Hover / Selected Checkbox (Matches find_ui.png)
        if is_selected or is_hovered:
            cb_rect = self.checkbox_rect(card_rect)
            if is_selected:
                painter.setBrush(QColor("#106EBE"))
                painter.setPen(QPen(QColor("#005A9E"), 1.2))
                painter.drawRoundedRect(cb_rect, 2, 2)
                painter.setPen(QPen(QColor("#FFFFFF"), 1.8))
                painter.drawLine(
                    cb_rect.left() + 3,
                    cb_rect.top() + 8,
                    cb_rect.left() + 7,
                    cb_rect.bottom() - 3,
                )
                painter.drawLine(
                    cb_rect.left() + 7,
                    cb_rect.bottom() - 3,
                    cb_rect.right() - 3,
                    cb_rect.top() + 4,
                )
            else:
                painter.setBrush(QColor(255, 255, 255, 220))
                painter.setPen(QPen(QColor("#7A9CC6"), 1.1))
                painter.drawRoundedRect(cb_rect, 2, 2)

        # 5. Top-Right Flag Pin Icon (shown only if 'flag' in visible details)
        if "flag" in self._visible_details or "all" in self._visible_details:
            if flag == 1 or is_hovered:
                fl_rect = self.flag_rect(card_rect)
                pole_x = fl_rect.left() + 4
                painter.setPen(
                    QPen(QColor("#D83B01") if flag == 1 else QColor("#8A9AB0"), 1.3)
                )
                painter.drawLine(pole_x, fl_rect.top() + 2, pole_x, fl_rect.bottom() - 2)
                banner = QPolygonF(
                    [
                        QPointF(pole_x, fl_rect.top() + 2),
                        QPointF(fl_rect.right() - 2, fl_rect.top() + 5),
                        QPointF(pole_x, fl_rect.top() + 9),
                    ]
                )
                painter.setBrush(
                    QColor("#E81123") if flag == 1 else QColor(255, 255, 255, 190)
                )
                painter.drawPolygon(banner)

        # 6. Extra detail lines (Filename, Size, Date, etc.)
        y_text = img_box.bottom() + 2
        if extra_lines:
            detail_font = QFont("Segoe UI", 8)
            painter.setFont(detail_font)
            painter.setPen(QColor("#333333"))
            fm = painter.fontMetrics()
            for line in extra_lines:
                elided = fm.elidedText(line, Qt.ElideMiddle, card_rect.width() - 12)
                painter.drawText(
                    QRect(card_rect.left() + 6, y_text, card_rect.width() - 12, 14),
                    Qt.AlignHCenter | Qt.AlignVCenter,
                    elided,
                )
                y_text += 14

        # 6b. Caption (Shown if 'caption' in visible details)
        if has_caption:
            cap_rect = self.caption_rect(card_rect, has_stars=has_stars)
            cap_text = str(index.data(CatalogRoles.CaptionRole) or "").strip()
            painter.save()
            is_cap_hovered = (self._hover_row == index.row() and getattr(self, "_hover_caption", False))
            if cap_text:
                cap_font = QFont("Segoe UI", 9)
                painter.setFont(cap_font)
                painter.setPen(QColor("#2B74B9") if is_cap_hovered else QColor("#333333"))
                fm = painter.fontMetrics()
                elided = fm.elidedText(cap_text, Qt.ElideMiddle, cap_rect.width())
                painter.drawText(cap_rect, Qt.AlignCenter, elided)
            else:
                cap_font = QFont("Segoe UI", 9)
                cap_font.setItalic(True)
                painter.setFont(cap_font)
                painter.setPen(QColor("#2B74B9") if is_cap_hovered else QColor("#888888"))
                painter.drawText(cap_rect, Qt.AlignCenter, "Add caption")
            painter.restore()

        # 7. Interactive 5-Star Rating Bar at Bottom of Card
        if "rating" in self._visible_details or "all" in self._visible_details:
            stars_rect = self.stars_bar_rect(card_rect)
            star_slot_w = stars_rect.width() / 5.0
            cy = stars_rect.center().y()
            is_card_star_hovered = (self._hover_row == index.row())
            hovered_star_num = self._hover_star if is_card_star_hovered else 0

            for s_idx in range(1, 6):
                cx = stars_rect.left() + (s_idx - 0.5) * star_slot_w
                poly = _build_star_polygon(cx, cy, outer_r=5.2, inner_r=2.3)
                if hovered_star_num > 0:
                    if s_idx <= hovered_star_num and s_idx <= rating:
                        # Stays rated: solid gold
                        painter.setBrush(QColor("#F5B800"))
                        painter.setPen(QPen(QColor("#C68B00"), 0.8))
                    elif hovered_star_num < s_idx <= rating:
                        # Would be removed: fade to translucent yellow to indicate removal
                        painter.setBrush(QColor(245, 184, 0, 70))
                        painter.setPen(QPen(QColor(198, 139, 0, 90), 0.8))
                    elif rating < s_idx <= hovered_star_num:
                        # Would be added: crisp hover outline preview
                        painter.setBrush(Qt.NoBrush)
                        painter.setPen(QPen(QColor("#4A90E2"), 1.2))
                    else:
                        # Inactive
                        painter.setBrush(Qt.NoBrush)
                        outline_col = QColor("#B09B6B") if (is_hovered or is_selected or rating > 0) else QColor("#D5C9A8")
                        painter.setPen(QPen(outline_col, 0.8))
                else:
                    if s_idx <= rating:
                        painter.setBrush(QColor("#F5B800"))
                        painter.setPen(QPen(QColor("#C68B00"), 0.8))
                    else:
                        painter.setBrush(Qt.NoBrush)
                        outline_col = QColor("#B09B6B") if (is_hovered or is_selected or rating > 0) else QColor("#D5C9A8")
                        painter.setPen(QPen(outline_col, 0.8))
                painter.drawPolygon(poly)

        painter.restore()

    # -------------------------------------------------------------------------
    # Interactive Hit-Testing (Stars, Flag, Checkbox, Collapsible Group Header)
    # -------------------------------------------------------------------------
    def editorEvent(
        self,
        event: QEvent,
        model: QAbstractItemModel,
        option: QStyleOptionViewItem,
        index: QModelIndex,
    ) -> bool:
        if event.type() == QEvent.MouseButtonRelease and isinstance(event, QMouseEvent):
            if event.button() == Qt.LeftButton:
                pos = event.position().toPoint()

                if index.data(CatalogRoles.IsHeaderSpacerRole):
                    return False

                if index.data(CatalogRoles.IsGroupHeaderRole):
                    gkey = str(index.data(CatalogRoles.GroupKeyRole) or "")
                    if gkey:
                        self.group_header_clicked.emit(gkey)
                        return True

                media_id = index.data(CatalogRoles.MediaIdRole)
                if media_id is None:
                    return False

                card_rect = option.rect.adjusted(2, 2, -2, -2)

                # 1. Check top-left checkbox hit
                if self.checkbox_rect(card_rect).contains(pos):
                    is_sel = bool(option.state & QStyle.State_Selected)
                    self.checkbox_toggled.emit(int(media_id), not is_sel)
                    return True

                # 2. Check top-right flag pin hit
                if self.flag_rect(card_rect).contains(pos):
                    curr_flag = int(index.data(CatalogRoles.FlagRole) or 0)
                    new_flag = 0 if curr_flag == 1 else 1
                    self.flag_toggled.emit(int(media_id), new_flag)
                    return True

                # 3. Check bottom 5-star rating bar hit
                stars_rect = self.stars_bar_rect(card_rect)
                star_hit = self.star_index_at(stars_rect, pos)
                if star_hit is not None:
                    curr_rating = int(index.data(CatalogRoles.RatingRole) or 0)
                    new_rating = 0 if curr_rating == star_hit else star_hit
                    self.rating_clicked.emit(int(media_id), new_rating)
                    return True

        return super().editorEvent(event, model, option, index)


class ThumbnailGridView(QListView):
    """
    Virtualized 2D Canvas View backed by CatalogListModel's O(G) geometry engine.
    Guarantees 38px full-width collapsible group headers and exact column-0 alignment
    for both WLPG Classic Grid ('wlpg_grid') and Tessellated Mosaic ('mosaic').
    """

    viewport_range_changed = Signal(list)         # list[int] of visible + buffer media_ids
    selection_ids_changed = Signal(list, int)     # selected_media_ids, lead_media_id (-1 if none)
    media_activated = Signal(int)                 # media_id on double-click or Enter
    _active_drag_button: Qt.MouseButton = Qt.LeftButton

    def __init__(
        self,
        model: CatalogListModel | None = None,
        delegate: MediaCardDelegate | None = None,
        parent: QWidget | None = None,
    ) -> None:
        super().__init__(parent)
        self._thumb_size = 150
        self._cell_padding = 14
        self._grid_spacing = 8
        self._hover_vrow: int = -1
        self._rubber_band_origin: QPoint | None = None
        self._rubber_band_current: QPoint | None = None
        self._drag_start_pos: QPoint | None = None
        self._drag_button: Qt.MouseButton = Qt.LeftButton
        self._last_drag_end_time: float = 0.0
        self._pending_single_select: QModelIndex | None = None
        self._press_index: QModelIndex = QModelIndex()
        self.scope_bar: SearchScopeBar | None = None

        self.setMouseTracking(True)
        self.viewport().setMouseTracking(True)
        self.setSelectionMode(QAbstractItemView.ExtendedSelection)
        self.setVerticalScrollMode(QAbstractItemView.ScrollPerPixel)
        self.setHorizontalScrollBarPolicy(Qt.ScrollBarAlwaysOff)
        self.setFrameShape(QListView.NoFrame)

