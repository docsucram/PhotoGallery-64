    # Visible Viewport Prefetch Range & Selection Helpers
    # -------------------------------------------------------------------------
    def visible_media_ids(self, buffer_rows: int = 2) -> list[int]:
        """Calculates the exact media_ids currently visible in the viewport plus buffer_rows."""
        if self.catalog_model is None or self.catalog_model.rowCount() == 0:
            return []

        _, cell_h = self._cell_dimensions()
        buf_px = max(120, buffer_rows * cell_h)
        scroll_y = max(0, self.verticalScrollBar().value())
        vp_h = max(cell_h, self.viewport().height())

        vrows = self.catalog_model.visible_vrows_in_rect(
            max(0, scroll_y - buf_px), scroll_y + vp_h + buf_px
        )
        media_ids: list[int] = []
        for vrow in vrows:
            idx = self.catalog_model.index(vrow, 0)
            mid = self.catalog_model.media_id_at(idx)
            if mid is not None:
                media_ids.append(mid)
        return media_ids

    def _emit_visible_range(self) -> None:
        self.viewport_range_changed.emit(self.visible_media_ids(buffer_rows=2))

    def _on_model_reset(self) -> None:
        self._sync_metrics_and_scrollbar()
        self._scroll_debounce.start()

    def selected_media_ids(self) -> list[int]:
        sel_model = self.selectionModel()
        if sel_model is None or self.catalog_model is None:
            return []
        return self.catalog_model.get_media_ids_for_selection(sel_model.selection())

    def selected_records(self) -> list[MediaItemRecord]:
        sel_model = self.selectionModel()
        if sel_model is None or self.catalog_model is None:
            return []
        return self.catalog_model.get_records_for_selection(sel_model.selection())

    def lead_selected_media_id(self) -> int | None:
        if self.catalog_model is None:
            return None
        curr = self.currentIndex()
        if curr.isValid():
            mid = self.catalog_model.media_id_at(curr)
            if mid is not None:
                return mid
        ids = self.selected_media_ids()
        return ids[0] if ids else None

    def on_card_checkbox_toggled(self, media_id: int, checked: bool) -> None:
        if self.catalog_model is None:
            return
        idx = self.catalog_model.index_for_media_id(media_id)
        if not idx.isValid() or self.selectionModel() is None:
            return
        sel_model = self.selectionModel()
        flag = (
            sel_model.SelectionFlag.Select
            if checked
            else sel_model.SelectionFlag.Deselect
        )
        sel_model.select(idx, flag)
        if checked:
            sel_model.setCurrentIndex(idx, sel_model.SelectionFlag.NoUpdate)

    def _on_selection_changed(self, _selected, _deselected) -> None:
        if self.catalog_model is None:
            return
        ids = self.selected_media_ids()
        self.catalog_model.set_selected_media_ids(ids)
        lead_id = self.lead_selected_media_id()
        self.selection_ids_changed.emit(ids, lead_id if lead_id is not None else -1)
        self.viewport().update()

    def select_media_id(self, media_id: int) -> None:
        """Selects a specific media_id in the grid and scrolls it into view."""
        if self.catalog_model is None or self.selectionModel() is None:
            return
        idx = self.catalog_model.index_for_media_id(media_id)
        if idx.isValid():
            self.selectionModel().clearSelection()
            self.selectionModel().select(idx, self.selectionModel().SelectionFlag.Select)
            self.selectionModel().setCurrentIndex(idx, self.selectionModel().SelectionFlag.NoUpdate)
            crect = self.catalog_model.item_rect(idx.row())
            if crect.isValid():
                sb = self.verticalScrollBar()
                sb.setValue(max(0, crect.top() - 40))
            self.viewport().update()

    def set_selected_media_ids(self, media_ids: Sequence[int], scroll_lead: bool = False) -> None:
        """Restores or sets selection to multiple media_ids without clearing unless requested."""
        if self.catalog_model is None or self.selectionModel() is None:
            return
        sel_model = self.selectionModel()
        sel_model.blockSignals(True)
        sel_model.clearSelection()
        first_valid: QModelIndex | None = None
        for mid in media_ids:
            idx = self.catalog_model.index_for_media_id(mid)
            if idx.isValid():
                if first_valid is None:
                    first_valid = idx
                sel_model.select(idx, sel_model.SelectionFlag.Select)
        if first_valid is not None and first_valid.isValid():
            sel_model.setCurrentIndex(first_valid, sel_model.SelectionFlag.NoUpdate)
        sel_model.blockSignals(False)
        ids = self.selected_media_ids()
        self.catalog_model.set_selected_media_ids(ids)
        lead_id = self.lead_selected_media_id()
        self.selection_ids_changed.emit(ids, lead_id if lead_id is not None else -1)
        if scroll_lead and first_valid is not None and first_valid.isValid():
            crect = self.catalog_model.item_rect(first_valid.row())
            if crect.isValid():
                sb = self.verticalScrollBar()
                sb.setValue(max(0, crect.top() - 40))
        self.viewport().update()

