    def keyPressEvent(self, event: QKeyEvent) -> None:
        if not (event.modifiers() & (Qt.ControlModifier | Qt.AltModifier)):
            if event.key() in (Qt.Key_Plus, Qt.Key_Equal) or event.text() in ("+", "="):
                main_win = getattr(self, "main_window", None) or self.window()
                if hasattr(main_win, "dispatch_ribbon_action"):
                    main_win.dispatch_ribbon_action("zoom_in")
                event.accept()
                return
            elif event.key() in (Qt.Key_Minus, Qt.Key_Underscore) or event.text() in ("-", "_"):
                main_win = getattr(self, "main_window", None) or self.window()
                if hasattr(main_win, "dispatch_ribbon_action"):
                    main_win.dispatch_ribbon_action("zoom_out")
                event.accept()
                return
            if Qt.Key_0 <= event.key() <= Qt.Key_5:
                rating_val = event.key() - Qt.Key_0
                main_win = getattr(self, "main_window", None) or self.window()
                if hasattr(main_win, "apply_rating_to_selection"):
                    main_win.apply_rating_to_selection(rating_val)
                    event.accept()
                    return
        super().keyPressEvent(event)

    def leaveEvent(self, event: QEvent) -> None:
        if self._hover_vrow != -1:
            self._hover_vrow = -1
        if self.card_delegate is not None:
            self.card_delegate._hover_row = -1
            self.card_delegate._hover_star = 0
            self.card_delegate._hover_caption = False
        self.viewport().update()
        super().leaveEvent(event)

    def viewportEvent(self, event: QEvent) -> bool:
        if event.type() == QEvent.ToolTip:
            pos = getattr(event, "pos", lambda: QPoint())()
            idx = self.indexAt(pos)
            if idx.isValid() and not idx.data(CatalogRoles.IsGroupHeaderRole):
                record = idx.data(CatalogRoles.RecordRole)
                if record is not None:
                    dt = _epoch_to_datetime_utc(record.date_taken) if record.date_taken else None
                    dt_str = dt.strftime("%d %B %Y %H:%M") if dt else ""
                    tip_text = f"{record.filename}\n{dt_str}" if dt_str else record.filename
                    g_pos = getattr(event, "globalPos", lambda: self.mapToGlobal(pos))()
                    QToolTip.showText(g_pos, tip_text, self.viewport())
                    return True
        return super().viewportEvent(event)

    def mouseReleaseEvent(self, event: QMouseEvent) -> None:
        if self._rubber_band_origin is not None:
            self._rubber_band_origin = None
            self._rubber_band_current = None
            self.viewport().update()
            return

        if self._pending_single_select is not None and self._pending_single_select.isValid():
            sel_model = self.selectionModel()
            if sel_model is not None:
                sel_model.select(self._pending_single_select, QItemSelectionModel.ClearAndSelect)
                sel_model.setCurrentIndex(self._pending_single_select, QItemSelectionModel.NoUpdate)
            self._pending_single_select = None

        self._drag_start_pos = None

        if self.catalog_model is None or self.card_delegate is None:
            return

        pos = event.position().toPoint()
        idx = self.indexAt(pos)
        if idx.isValid():
            opt = QStyleOptionViewItem()
            opt.rect = self.visualRect(idx)
            if self.selectionModel() is not None and self.selectionModel().isSelected(idx):
                opt.state |= QStyle.State_Selected
            if self.card_delegate.editorEvent(event, self.catalog_model, opt, idx):
                self.viewport().update()
                return

    def mouseDoubleClickEvent(self, event: QMouseEvent) -> None:
        if event.button() == Qt.LeftButton and self.catalog_model is not None:
            pos = event.position().toPoint()
            idx = self.indexAt(pos)
            if idx.isValid():
                if idx.data(CatalogRoles.IsGroupHeaderRole):
                    gkey = str(idx.data(CatalogRoles.GroupKeyRole) or "")
                    if gkey:
                        self.catalog_model.toggle_group_collapsed(gkey)
                    return
                mid = self.catalog_model.media_id_at(idx)
                if mid is not None:
                    self.media_activated.emit(mid)
                    return

    def contextMenuEvent(self, event: QContextMenuEvent) -> None:
        if self.catalog_model is None:
            return
        if time.monotonic() - getattr(self, "_last_drag_end_time", 0.0) < 0.3:
            event.ignore()
            return
        pos = event.pos()
        idx = self.indexAt(pos)

        if idx.isValid() and not idx.data(CatalogRoles.IsGroupHeaderRole):
            sel_model = self.selectionModel()
            if sel_model is not None and not sel_model.isSelected(idx):
                sel_model.select(idx, QItemSelectionModel.ClearAndSelect)
                sel_model.setCurrentIndex(idx, QItemSelectionModel.NoUpdate)
            mid = self.catalog_model.media_id_at(idx)
            is_video = bool(idx.data(CatalogRoles.IsVideoRole))
            if mid is not None:
                self._show_card_context_menu(event.globalPos(), mid, is_video=is_video)
        else:
            self._show_background_context_menu(event.globalPos())

